// Builds app/src/main/assets/web/gen from code shared with the Windows app:
//  - core.js: src/core (CommonJS) + the Android parts in web/core, bundled into one plain script
//    that defines globalThis.BestCore. Every require() is resolved here at build time; the bundle
//    contains no loader that could fetch code at run time.
//  - i18n.js, dom.js: the Windows UI's strings and DOM helpers (ES modules, copied as they are).
//  - fonts/: the same local fonts (no font is ever loaded from the network).
// Plain Node, no packages. Output is deterministic, so unchanged sources give unchanged files.

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const androidDir = resolve(here, '..');
const repo = resolve(androidDir, '..');
const out = join(androidDir, 'app', 'src', 'main', 'assets', 'web', 'gen');
const entry = join(androidDir, 'web', 'core', 'index.js');

// Node built-ins used by `yaml` only for debug warnings and binary scalars.
const SHIMS = {
  process: 'module.exports = { env: {} };',
  buffer: 'module.exports = {};',
};

function resolveFile(from, spec) {
  if (SHIMS[spec]) return `shim:${spec}`;
  let base;
  if (spec.startsWith('.')) base = resolve(dirname(from), spec);
  else if (spec === 'yaml') base = join(repo, 'node_modules', 'yaml', 'dist', 'index.js');
  else throw new Error(`${relative(repo, from)}: require('${spec}') is not allowed in the Android bundle`);
  for (const p of [base, `${base}.js`, join(base, 'index.js')]) {
    if (existsSync(p) && statSync(p).isFile()) return p;
  }
  throw new Error(`${relative(repo, from)}: cannot resolve '${spec}'`);
}

const REQUIRE = /\brequire\(\s*(['"])([^'"]+)\1\s*\)/g;
const modules = new Map(); // id -> { code, deps: {spec: id} }
const idOf = (p) => (p.startsWith('shim:') ? p : relative(repo, p).split(sep).join('/'));

function add(file) {
  const id = idOf(file);
  if (modules.has(id)) return id;
  if (file.startsWith('shim:')) { modules.set(id, { code: SHIMS[file.slice(5)], deps: {} }); return id; }
  const code = readFileSync(file, 'utf8');
  const mod = { code, deps: {} };
  modules.set(id, mod);
  for (const m of code.matchAll(REQUIRE)) {
    const spec = m[2];
    if (!(spec in mod.deps)) mod.deps[spec] = add(resolveFile(file, spec));
  }
  return id;
}

const entryId = add(entry);
const ids = [...modules.keys()].sort();
let bundle = '/* Generated by android/scripts/build-web.mjs from src/core and android/web/core. Do not edit. */\n';
bundle += '(function () {\n"use strict";\nconst defs = Object.create(null);\nconst cache = Object.create(null);\n';
bundle += 'function load(id) {\n  if (cache[id]) return cache[id].exports;\n  const def = defs[id];\n  if (!def) throw new Error("missing module " + id);\n  const module = { exports: {} };\n  cache[id] = module;\n  def.fn(module, module.exports, (spec) => {\n    const dep = def.deps[spec];\n    if (!dep) throw new Error("unknown require " + spec + " in " + id);\n    return load(dep);\n  });\n  return module.exports;\n}\n';
for (const id of ids) {
  const m = modules.get(id);
  bundle += `defs[${JSON.stringify(id)}] = { deps: ${JSON.stringify(m.deps)}, fn: function (module, exports, require) {\n${m.code}\n} };\n`;
}
bundle += `globalThis.BestCore = Object.freeze(load(${JSON.stringify(entryId)}));\n})();\n`;

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'fonts'), { recursive: true });
writeFileSync(join(out, 'core.js'), bundle);
for (const f of ['i18n.js', 'dom.js']) copyFileSync(join(repo, 'renderer', f), join(out, f));
for (const f of readdirSync(join(repo, 'renderer', 'fonts'))) {
  if (f.endsWith('.woff2')) copyFileSync(join(repo, 'renderer', 'fonts', f), join(out, 'fonts', f));
}
console.log(`web/gen: core.js (${modules.size} modules, ${(bundle.length / 1024).toFixed(0)} KB), i18n.js, dom.js, fonts`);
